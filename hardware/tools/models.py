#!/usr/bin/env python3
"""Write simple VRML box models into cn105.3dshapes for parts whose official
models are missing from this KiCad install.  Dimensions from the datasheets;
these are placeholders for the 3D viewer and interference checks, not art.

KiCad VRML convention: 1 unit = 2.54 mm, X = board x, Y = -board y, Z = up.
"""
import os, sys
OUT = os.path.join(sys.argv[1] if len(sys.argv) > 1 else ".", "cn105.3dshapes")
os.makedirs(OUT, exist_ok=True)
U = 2.54

def box(cx, cy, z0, sx, sy, sz, rgb, shiny=0.2):
    """box centred at footprint (cx, cy) mm, from height z0 to z0+sz."""
    return f"""Transform {{
  translation {cx/U:.4f} {-cy/U:.4f} {(z0 + sz/2)/U:.4f}
  children [ Shape {{
    appearance Appearance {{ material Material {{ diffuseColor {rgb[0]} {rgb[1]} {rgb[2]} specularColor 0.3 0.3 0.3 shininess {shiny} }} }}
    geometry Box {{ size {sx/U:.4f} {sy/U:.4f} {sz/U:.4f} }}
  }} ]
}}
"""

def write(name, parts):
    with open(os.path.join(OUT, name + ".wrl"), "w") as f:
        f.write("#VRML V2.0 utf8\n# placeholder model generated by tools/models.py\n" + "".join(parts))
    print("wrote", name + ".wrl")

WHITE = (0.92, 0.92, 0.86); METAL = (0.72, 0.73, 0.75); PCB = (0.10, 0.35, 0.18); BLACK = (0.12, 0.12, 0.12)

# JST PA B05B-PASK: housing 12 x 5.3 x 7.7 mm; pins at y=0, back face at +2.2, front at -3.1
write("JST_PA_B05B-PASK_1x05_P2.00mm_Vertical", [
    box(4.0, -0.45, 0, 12.0, 5.3, 7.7, WHITE),
    box(4.0, -0.45, 6.2, 10.4, 3.7, 1.6, BLACK),          # plug cavity at the top
])

# JST PA S05B-PASK-2 side entry: housing 12 x 8.2 x 6.5 mm, back face at y=-1.0, opening at y=+7.2
write("JST_PA_S05B-PASK-2_1x05_P2.00mm_Horizontal", [
    box(4.0, 3.1, 0, 12.0, 8.2, 6.5, WHITE),
    box(4.0, 6.3, 1.4, 10.4, 1.9, 3.7, BLACK),           # plug opening on the front face
])

